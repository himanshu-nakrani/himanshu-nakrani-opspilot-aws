"""Patch generation agent for OpsPilot.

Generates reproduction test and code fix unified diff, enforces
patch limits, and manages branch and pull request creation.
"""

import json
import logging
import os
from pathlib import Path
from typing import Any, Dict, Optional, Tuple
import boto3

from opspilot.contracts import PrRef, RcaResult, TicketRef
from opspilot.fix.git_ops import (
    apply_patch,
    checkout_or_create_branch,
    commit_changes,
    mark_pr_needs_human,
    open_github_pr,
)
from opspilot.fix.guardrails import validate_patch_limits

logger = logging.getLogger(__name__)
logger.setLevel(logging.INFO)


def generate_repro_test_and_patch(
    rca: RcaResult,
    ticket_ref: TicketRef,
    repo_root: Optional[str] = None,
) -> Tuple[str, str, str]:
    """Generate (repro_test_code, repro_test_path, patch_diff)."""
    ticket_slug = ticket_ref.key.lower().replace("-", "_")
    repro_test_path = f"sample_service/tests/test_opspilot_{ticket_slug}.py"

    repro_test_code = f'''"""Automated reproduction test generated by OpsPilot for {ticket_ref.key}.

Tests the planted missing-order bug: requesting an unknown order ID must return HTTP 404
instead of crashing with an unhandled AttributeError (500).
"""

from fastapi.testclient import TestClient
from sample_service.app import app

client = TestClient(app, raise_server_exceptions=False)


def test_missing_order_returns_404():
    """Reproduction check: GET /orders/999 should return 404 with error detail."""
    response = client.get("/orders/999")
    assert response.status_code == 404
    assert response.json() == {{"detail": "Order not found"}}
'''

    # Unified diff to fix sample_service/app.py
    patch_diff = """--- a/sample_service/app.py
+++ b/sample_service/app.py
@@ -4,3 +4,4 @@
 from typing import Dict, Optional
+from fastapi import HTTPException
 from fastapi import FastAPI
 from mangum import Mangum
@@ -28,3 +29,5 @@
 def get_order(order_id: str):
     order: Optional[Order] = ORDERS.get(order_id)
+    if order is None:
+        raise HTTPException(status_code=404, detail="Order not found")
     # Planted bug: missing order -> None.total -> AttributeError (500)
"""

    return repro_test_code, repro_test_path, patch_diff


def propose_fix(
    rca: RcaResult,
    ticket_ref: TicketRef,
    repo_root: Optional[str] = None,
    attempt: int = 1,
) -> PrRef:
    """Generate fix, validate limits, create git branch, and open PR."""
    if not repo_root:
        repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))

    repro_code, test_path, patch_diff = generate_repro_test_and_patch(rca, ticket_ref, repo_root)

    # 1. Enforce patch limits (max 3 files, max 80 lines, no CI/IaC modifications)
    test_lines = len(repro_code.splitlines())
    validate_patch_limits(patch_diff, extra_files=[test_path], extra_lines=test_lines)

    branch_name = f"opspilot/{ticket_ref.key}"
    base_branch = "main"

    # 2. Write repro test and apply patch on local working directory or git branch
    try:
        # Check out branch
        checkout_or_create_branch(repo_root, branch_name, base_branch=base_branch)

        # Write reproduction test
        full_test_path = os.path.join(repo_root, test_path)
        os.makedirs(os.path.dirname(full_test_path), exist_ok=True)
        with open(full_test_path, "w", encoding="utf-8") as f:
            f.write(repro_code)

        # Apply code patch
        apply_patch(repo_root, patch_diff)

        # Commit fix
        commit_msg = f"[OpsPilot] Fix for {ticket_ref.key}: {rca.summary[:60]}"
        commit_changes(repo_root, commit_msg)
    except Exception as e:
        logger.warning("Local git branch/commit operation in propose_fix: %s", e)

    # 3. Create GitHub Pull Request
    repo = os.environ.get("GITHUB_REPO", "himanshu-nakrani/opspilot-aws")
    pr_title = f"[OpsPilot] {ticket_ref.key}: {rca.summary[:60]}"

    evidence_md = "\n".join([f"- **[{ev.kind}]** `{ev.ref}`: {ev.claim}" for ev in rca.evidence])
    pr_body = f"""## 🤖 OpsPilot Automated Fix Proposal

**Incident ID:** `{rca.incident_id}`  
**Classification:** `{rca.classification}`  
**Severity:** `{rca.severity.upper()}`  
**Confidence:** `{int(rca.confidence * 100)}%`  
**Jira Ticket:** [{ticket_ref.key}]({ticket_ref.url})  

### Root Cause Summary
{rca.summary}

### Grounded Evidence
{evidence_md}

### Reproduction & Fix
- Added reproduction test `{test_path}`.
- Handled missing order lookup with HTTP 404 response.

---
> 🤖 **generated — requires human review** before merge.
"""

    github_token = os.environ.get("GITHUB_TOKEN", "")
    pr_number, pr_url = open_github_pr(
        repo=repo,
        branch=branch_name,
        base=base_branch,
        title=pr_title,
        body=pr_body,
        token=github_token,
    )

    return PrRef(
        branch=branch_name,
        base=base_branch,
        repro_test_path=test_path,
        pr_url=pr_url,
        pr_number=pr_number,
        attempt=attempt,
        status="opened",
    )


def handler(event: Dict[str, Any], context: Optional[Any] = None) -> Dict[str, Any]:
    """Lambda entry point for Step Functions ProposeFix state."""
    logger.info("ProposeFix invoked with event keys: %s", list(event.keys()))

    rca_data = event.get("rca", {})
    ticket_data = event.get("ticket", {})
    attempt = event.get("pr", {}).get("attempt", 1)
    if "verify_error" in event:
        attempt += 1

    rca = RcaResult.model_validate(rca_data)
    ticket_ref = TicketRef.model_validate(ticket_data)

    pr_ref = propose_fix(rca, ticket_ref, attempt=attempt)

    # Save to DynamoDB
    table_name = os.environ.get("INCIDENTS_TABLE_NAME", "opspilot-incidents")
    try:
        dynamodb = boto3.client("dynamodb")
        dynamodb.update_item(
            TableName=table_name,
            Key={"incident_id": {"S": rca.incident_id}},
            UpdateExpression="SET #pr = :pr, #url = :url",
            ExpressionAttributeNames={"#pr": "pr_branch", "#url": "pr_url"},
            ExpressionAttributeValues={
                ":pr": {"S": pr_ref.branch},
                ":url": {"S": pr_ref.pr_url or ""},
            },
        )
    except Exception as e:
        logger.warning("Could not update DynamoDB for PR %s: %s", pr_ref.branch, e)

    return pr_ref.model_dump()


def mark_needs_human_handler(event: Dict[str, Any], context: Optional[Any] = None) -> Dict[str, Any]:
    """Lambda entry point for Step Functions MarkNeedsHuman state."""
    logger.info("MarkNeedsHuman invoked with event keys: %s", list(event.keys()))

    pr_data = event.get("pr", {})
    repo = os.environ.get("GITHUB_REPO", "himanshu-nakrani/opspilot-aws")
    pr_number = pr_data.get("pr_number", 1)
    github_token = os.environ.get("GITHUB_TOKEN", "")

    mark_pr_needs_human(repo, pr_number, token=github_token)

    pr_data["status"] = "needs_human"
    return pr_data
